// Command sitegen writes the project page (docs/index.html and
// docs/<lang>/index.html) from the template docs/site/page.html and the
// texts in docs/site/lang/<lang>.json. Run it from the repository root
// after changing either:
//
//	go run ./tools/sitegen
//
// A test checks that the pages in docs/ are up to date.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"html/template"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// base is where GitHub Pages serves docs/.
const base = "https://i234dev.github.io/MyMule/"

// langs are the page's languages, in menu order; English is the default
// and lives at the root.
var langs = []struct{ Code, Name string }{
	{"en", "English"},
	{"es", "Español"},
	{"fr", "Français"},
	{"it", "Italiano"},
	{"de", "Deutsch"},
	{"pt", "Português"},
}

// faq lists the questions, in order; each has faq_<id>_q and faq_<id>_a
// texts.
var faq = []string{"emule", "highid", "safe", "legal", "why", "missing", "free"}

const header = "<!-- Generated by 'go run ./tools/sitegen' from docs/site/page.html and\n     docs/site/lang/%s.json: edit those, not this file. -->\n"

func main() {
	pages, err := render(".")
	if err != nil {
		fmt.Fprintln(os.Stderr, "sitegen:", err)
		os.Exit(1)
	}
	for _, p := range sortedKeys(pages) {
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err == nil {
			err = os.WriteFile(p, pages[p], 0o644)
		}
		if err != nil {
			fmt.Fprintln(os.Stderr, "sitegen:", err)
			os.Exit(1)
		}
		fmt.Println("wrote", p)
	}
}

type langLink struct {
	Code, Name, Label, Href, URL string
	Current                      bool
}

// render returns every page, keyed by its path relative to root (the
// repository's root).
func render(root string) (map[string][]byte, error) {
	src, err := os.ReadFile(filepath.Join(root, "docs", "site", "page.html"))
	if err != nil {
		return nil, err
	}
	// The pages always get LF line ends, also from a Windows checkout
	// that turned the template into CRLF.
	src = bytes.ReplaceAll(src, []byte("\r\n"), []byte("\n"))
	texts := map[string]map[string]string{}
	for _, l := range langs {
		data, err := os.ReadFile(filepath.Join(root, "docs", "site", "lang", l.Code+".json"))
		if err != nil {
			return nil, err
		}
		m := map[string]string{}
		if err := json.Unmarshal(data, &m); err != nil {
			return nil, fmt.Errorf("%s.json: %w", l.Code, err)
		}
		texts[l.Code] = m
	}
	// Every language must have exactly the English keys.
	for _, l := range langs[1:] {
		for k := range texts["en"] {
			if _, ok := texts[l.Code][k]; !ok {
				return nil, fmt.Errorf("%s.json: missing %q", l.Code, k)
			}
		}
		for k := range texts[l.Code] {
			if _, ok := texts["en"][k]; !ok {
				return nil, fmt.Errorf("%s.json: %q is not in en.json", l.Code, k)
			}
		}
	}

	pages := map[string][]byte{}
	for _, cur := range langs {
		t := texts[cur.Code]
		missing := func(k string) (string, error) {
			v, ok := t[k]
			if !ok {
				return "", fmt.Errorf("no text %q", k)
			}
			return v, nil
		}
		funcs := template.FuncMap{
			// t: a text for the page body; it may contain markup.
			"t": func(k string) (template.HTML, error) {
				v, err := missing(k)
				return template.HTML(v), err
			},
			// a: a plain text, for attributes and the title.
			"a": func(k string) (string, error) {
				v, err := missing(k)
				if strings.ContainsAny(v, "<&") {
					return "", fmt.Errorf("%s.json: %q is used as plain text: no markup or entities", cur.Code, k)
				}
				return v, err
			},
		}
		tmpl, err := template.New("page").Funcs(funcs).Parse(string(src))
		if err != nil {
			return nil, err
		}
		rel := "" // from this page to docs/
		if cur.Code != "en" {
			rel = "../"
		}
		var links []langLink
		for _, l := range langs {
			href := rel
			url := base
			if l.Code != "en" {
				href += l.Code + "/"
				url += l.Code + "/"
			}
			if href == "" {
				href = "./"
			}
			links = append(links, langLink{l.Code, l.Name, strings.ToUpper(l.Code), href, url, l.Code == cur.Code})
		}
		url := base
		if cur.Code != "en" {
			url += cur.Code + "/"
		}
		var b bytes.Buffer
		err = tmpl.Execute(&b, map[string]any{
			"Lang": cur.Code, "Root": rel, "URL": url, "Base": base,
			"Langs": links, "FAQ": faq,
		})
		if err != nil {
			return nil, fmt.Errorf("%s: %w", cur.Code, err)
		}
		out := b.String()
		out = strings.Replace(out, "<!doctype html>\n", "<!doctype html>\n"+fmt.Sprintf(header, cur.Code), 1)
		path := filepath.Join("docs", "index.html")
		if cur.Code != "en" {
			path = filepath.Join("docs", cur.Code, "index.html")
		}
		pages[path] = []byte(out)
	}
	return pages, nil
}

func sortedKeys(m map[string][]byte) []string {
	var keys []string
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
